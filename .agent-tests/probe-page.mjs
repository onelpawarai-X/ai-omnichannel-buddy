import { chromium } from "playwright";
const b = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox","--disable-dev-shm-usage"] });
const p = await b.newPage({ viewport: { width: 1680, height: 1000 } });
const errs = [];
p.on("pageerror", (e) => errs.push("pageerror: " + String(e).slice(0, 300)));
p.on("console", (m) => { if (m.type() === "error") errs.push("console: " + m.text().slice(0, 300)); });
const resp = await p.goto("http://127.0.0.1:12000/", { waitUntil: "domcontentloaded", timeout: 90000 });
console.log("status", resp?.status());
await p.waitForTimeout(6000);
console.log("title", await p.title());
console.log("buttons:", (await p.locator("button").allTextContents()).slice(0, 25));
console.log("errors:", errs.slice(0, 6));
await p.screenshot({ path: "/tmp/zb/probe-page.png" });
await b.close();
